import type { Node } from "@vango-panel/db";

export type PanelEndpoints = {
  /** URL wings uses to call the panel's /api/remote. */
  remote: string;
  /** Browser origins the panel is served from (checked by wings' websocket + CORS). */
  allowedOrigins: string[];
};

export function nodeConfigYaml(
  node: Pick<Node, "id" | "url" | "sftpPort" | "tokenId">,
  token: string,
  panel: PanelEndpoints,
) {
  const u = new URL(node.url);
  const port = u.port ? Number(u.port) : u.protocol === "https:" ? 443 : 80;
  const remote = panel.remote.replace(/\/+$/, "");
  const origins = [...new Set(panel.allowedOrigins.map((o) => new URL(o).origin))];
  const q = (s: string) => JSON.stringify(s);
  return [
    "# Generated by vango-panel. Keep this file secret: it contains the node token.",
    `uuid: ${q(node.id)}`,
    `token_id: ${q(node.tokenId)}`,
    `token: ${q(token)}`,
    `remote: ${q(remote)}`,
    `allowed_origins: [${origins.map(q).join(", ")}]`,
    "api:",
    "  host: 0.0.0.0",
    `  port: ${port}`,
    ...(u.protocol === "https:"
      ? ["  ssl:", "    enabled: true", "    cert: /etc/letsencrypt/live/<fqdn>/fullchain.pem", "    key: /etc/letsencrypt/live/<fqdn>/privkey.pem"]
      : []),
    "system:",
    "  sftp:",
    `    bind_port: ${node.sftpPort}`,
    "",
  ].join("\n");
}
